// Preset describes how one AI tool expects its project instructions: where
// the file lives and what front matter the tool needs around the Markdown.
type Preset struct {
	Name        string
	Tool        string
	Path        string
	Frontmatter string
	// Legacy lists older locations the tool also reads; `import` picks them up.
	Legacy []string
}

