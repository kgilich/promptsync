var DefaultTools = []string{"agents", "claude", "copilot", "cursor"}

// Presets returns all built-in presets sorted by name.
func Presets() []Preset {
	result := make([]Preset, 0, len(presets))
	for _, preset := range presets {
		result = append(result, preset)
	}
	sort.Slice(result, func(i, j int) bool { return result[i].Name < result[j].Name })
	return result
}

func lookupPreset(name string) (Preset, error) {
	preset, ok := presets[strings.ToLower(strings.TrimSpace(name))]
	if !ok {
		names := make([]string, 0, len(presets))
		for _, p := range Presets() {
			names = append(names, p.Name)
		}
		return Preset{}, fmt.Errorf("unknown preset %q; available: %s", name, strings.Join(names, ", "))
	}
	return preset, nil
}

const generatedBannerFormat = "<!-- Generated by PromptSync from %s. Do not edit; change the source and run 'promptsync sync'. -->"

// renderPreset wraps rendered Markdown in the preset's front matter and a
// generated-file banner so humans know where to make edits.
func renderPreset(preset Preset, source, content string) string {
	var out strings.Builder
	out.WriteString(preset.Frontmatter)
	fmt.Fprintf(&out, generatedBannerFormat, source)
	out.WriteString("\n\n")
	out.WriteString(strings.TrimLeft(content, "\n"))
	return out.String()
}
