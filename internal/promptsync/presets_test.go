package promptsync

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestPresetTargetsUseToolPathsAndFrontmatter(t *testing.T) {
	root := t.TempDir()
	writeTestFile(t, root, "promptsync.yaml", "version: 1\nsource: master.md\ntargets:\n  - preset: claude\n  - preset: cursor\n  - preset: copilot\n    path: docs/copilot.md\n")
	writeTestFile(t, root, "master.md", "# Rules\n")

	if _, err := Sync(filepath.Join(root, "promptsync.yaml")); err != nil {
		t.Fatalf("Sync() error = %v", err)
	}
	claude := readTestFile(t, root, "CLAUDE.md")
	if !strings.HasPrefix(claude, "<!-- Generated by PromptSync from master.md") || !strings.HasSuffix(claude, "# Rules\n") {
		t.Fatalf("CLAUDE.md = %q", claude)
	}
	cursor := readTestFile(t, root, ".cursor/rules/promptsync.mdc")
	if !strings.HasPrefix(cursor, "---\n") || !strings.Contains(cursor, "alwaysApply: true") {
		t.Fatalf("cursor rule lacks front matter: %q", cursor)
	}
	readTestFile(t, root, "docs/copilot.md")
}

func TestConfigRejectsUnknownPresetAndPresetWithTemplate(t *testing.T) {
	for name, target := range map[string]string{
		"unknown":  "  - preset: nope\n",
		"template": "  - preset: claude\n    template: t.tmpl\n",
	} {
		root := t.TempDir()
		writeTestFile(t, root, "promptsync.yaml", "version: 1\nsource: master.md\ntargets:\n"+target)
		if _, err := Inspect(filepath.Join(root, "promptsync.yaml")); err == nil {
			t.Fatalf("%s: config unexpectedly accepted", name)
		}
	}
}

func TestImportMergesExistingFilesAndRoundTrips(t *testing.T) {
	root := t.TempDir()
	writeTestFile(t, root, "CLAUDE.md", "# Shared\nUse {{ braces }}.\n")
	writeTestFile(t, root, "AGENTS.md", "# Shared\nUse {{ braces }}.\n")
	writeTestFile(t, root, ".cursorrules", "Prefer tabs.\n")

	result, err := Import(root)
	if err != nil {
		t.Fatalf("Import() error = %v", err)
	}
	if len(result.Tools) != 3 {
		t.Fatalf("tools = %v", result.Tools)
	}
	master := readTestFile(t, root, "prompts/master.md")
	if strings.Count(master, "# Shared") != 1 || !strings.Contains(master, "Prefer tabs.") {
		t.Fatalf("master = %q", master)
	}
	if _, err := SyncWithOptions(filepath.Join(root, "promptsync.yaml"), SyncOptions{Force: true}); err != nil {
		t.Fatalf("sync after import: %v", err)
	}
	if got := readTestFile(t, root, "CLAUDE.md"); !strings.Contains(got, "Use {{ braces }}.") {
		t.Fatalf("braces not preserved: %q", got)
	}
	if _, err := Import(root); err == nil {
		t.Fatal("Import() overwrote existing config")
	}
}

func TestImportFailsWithoutInstructionFiles(t *testing.T) {
	if _, err := Import(t.TempDir()); err == nil {
		t.Fatal("Import() succeeded on an empty project")
	}
}

func readTestFile(t *testing.T, root, path string) string {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(path)))
	if err != nil {
		t.Fatalf("read %s: %v", path, err)
	}
	return string(data)
}
