package promptsync

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	yaml "gopkg.in/yaml.v3"
)

// ImportResult describes what Import found and created.
type ImportResult struct {
	// Imported lists the existing instruction files that were read.
	Imported []string
	// Tools lists the presets configured as targets.
	Tools []string
	// Leftover lists legacy files whose content was imported but which are not
	// regenerated; the user should delete them to avoid duplicate rules.
	Leftover []string
	// Differing is true when files had different content, so master.md holds
	// several sections that every tool will receive.
	Differing bool
}

// Import adopts instruction files that already exist in a project: it merges
// them into prompts/master.md and writes a promptsync.yaml targeting the same
// tools. Existing files are not touched; the first `sync` reports them as
// modified until the user runs `sync --force` to switch them to generated output.
func Import(root string) (ImportResult, error) {
	absRoot, err := filepath.Abs(root)
	if err != nil {
		return ImportResult{}, fmt.Errorf("resolve project directory: %w", err)
	}

	type found struct {
		path    string
		content string
	}
	var files []found
	var tools []string
	for _, preset := range Presets() {
		candidates := append([]string{preset.Path}, preset.Legacy...)
		matched := false
		for _, candidate := range candidates {
			data, err := os.ReadFile(filepath.Join(absRoot, filepath.FromSlash(candidate)))
			if err != nil {
				continue // missing, or a directory such as .clinerules/
			}
			content := cleanImported(string(data))
			if content == "" {
				continue
			}
			files = append(files, found{path: candidate, content: content})
			matched = true
		}
		if matched {
			tools = append(tools, preset.Name)
		}
	}
	if len(files) == 0 {
		return ImportResult{}, fmt.Errorf("no existing AI instruction files found in %s; use 'promptsync init' instead", absRoot)
	}

	// Group files with identical content so shared rules are imported once.
	var groups []struct {
		paths   []string
		content string
	}
next:
	for _, file := range files {
		for index := range groups {
			if groups[index].content == file.content {
				groups[index].paths = append(groups[index].paths, file.path)
				continue next
			}
		}
		groups = append(groups, struct {
			paths   []string
			content string
		}{[]string{file.path}, file.content})
	}

	var master strings.Builder
	for index, group := range groups {
		if len(groups) > 1 {
			if index > 0 {
				master.WriteString("\n")
			}
			fmt.Fprintf(&master, "<!-- Imported from %s -->\n", strings.Join(group.paths, ", "))
		}
		master.WriteString(escapeTemplate(group.content))
		master.WriteString("\n")
	}

	config, err := buildConfig("prompts/master.md", nil, tools)
	if err != nil {
		return ImportResult{}, err
	}
	if err := writeNewFiles(absRoot, []starterFile{
		{path: "promptsync.yaml", content: config},
		{path: "prompts/master.md", content: master.String()},
	}); err != nil {
		return ImportResult{}, err
	}

	result := ImportResult{Tools: tools, Differing: len(groups) > 1}
	for _, file := range files {
		if !isPresetPath(file.path) {
			result.Leftover = append(result.Leftover, file.path)
		}
	}
	for _, file := range files {
		result.Imported = append(result.Imported, file.path)
	}
	return result, nil
}

// cleanImported strips front matter and a previous PromptSync banner so only
// the instructions themselves are imported.
func cleanImported(text string) string {
	text = canonicalizeLineEndings(text)
	if rest, ok := stripFrontmatter(text); ok {
		text = rest
	}
	lines := strings.Split(text, "\n")
	for len(lines) > 0 && (strings.TrimSpace(lines[0]) == "" || strings.HasPrefix(lines[0], "<!-- Generated by PromptSync")) {
		lines = lines[1:]
	}
	return strings.TrimRight(strings.Join(lines, "\n"), "\n ")
}

// escapeTemplate keeps literal "{{" in imported text from being parsed as a
// Go template action when the source is rendered.
func escapeTemplate(text string) string {
	return strings.ReplaceAll(text, "{{", `{{"{{"}}`)
}

func isPresetPath(path string) bool {
	for _, preset := range presets {
		if preset.Path == path {
			return true
		}
	}
	return false
}

// stripFrontmatter removes a leading YAML block (--- ... ---) only when it
// really is a YAML mapping, so a file that opens with a Markdown horizontal
// rule keeps its content.
func stripFrontmatter(text string) (string, bool) {
	if !strings.HasPrefix(text, "---\n") {
		return text, false
	}
	body := text[4:]
	var block, rest string
	switch {
	case strings.HasPrefix(body, "---\n"): // empty front matter
		return body[4:], true
	case strings.HasPrefix(body, "---") && strings.TrimSpace(body[3:]) == "":
		return "", true
	default:
		end := strings.Index(body, "\n---\n")
		if end < 0 {
			if !strings.HasSuffix(body, "\n---") {
				return text, false
			}
			block, rest = strings.TrimSuffix(body, "\n---"), ""
		} else {
			block, rest = body[:end], body[end+5:]
		}
	}
	var mapping map[string]any
	if err := yaml.Unmarshal([]byte(block), &mapping); err != nil || len(mapping) == 0 {
		return text, false
	}
	return rest, true
}
